import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
import os from 'node:os';
import { normalizeMessage, wrapStreamFn } from './normalize.js';
const { r: isLong, t: classify } = await import(pathToFileURL(os.homedir() + '/.openclaw/runtime/current/lib/node_modules/openclaw/dist/retry-evidence-BU61_01P.mjs'));
const raw = '429 All models exhausted: 1 route checked (1 rate-limited or on cooldown). Soonest reset ~17h.';
assert.equal(isLong(raw), false);
assert.equal(isLong(normalizeMessage(raw)), true);
assert.equal(classify(normalizeMessage(raw)).kind, 'long');
for (const text of ['429 too many requests, retry-after: 30 seconds', '503 unavailable', 'All models exhausted: Soonest reset ~17h.', 'OK']) assert.equal(normalizeMessage(text), text);
assert.equal(normalizeMessage(normalizeMessage(raw)), normalizeMessage(raw));
const model = {provider:'litellm-free-perso', api:'openai-completions', baseUrl:'https://litellm.gangneux.org/v1'};
const error = {errorMessage:raw};
const stream = {async *[Symbol.asyncIterator]() {yield {type:'error',error};}, async result(){return error;}};
const wrapped = wrapStreamFn({model,streamFn:()=>stream})(model,{},{});
for await (const event of wrapped) assert.equal(isLong(event.error.errorMessage),true);
assert.equal(isLong((await wrapped.result()).errorMessage),true);
const pass = () => stream;
assert.equal(wrapStreamFn({model:{...model,provider:'other'},streamFn:pass}),pass);
console.log('PASS: native long-window classifier, temporary errors unchanged, iterator and result, scope guard. Network calls=0');
